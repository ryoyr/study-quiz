import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(await readFile(resolve(root, "public/content/manifest.json"), "utf8"));
const output = resolve(root, "workers/quiz-content-db/migrations/0002_seed_content.sql");

const stable = (value) => {
  if (Array.isArray(value)) return value.map(stable);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(Object.keys(value).sort().map((key) => [key, stable(value[key])]));
};
const fingerprint = (question) => {
  const text = JSON.stringify(stable(question));
  let hash = 0x811c9dc5;
  for (let index = 0; index < text.length; index += 1) {
    hash ^= text.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(16).padStart(8, "0");
};
const sql = (value) => value === undefined || value === null
  ? "NULL"
  : typeof value === "number"
    ? String(value)
    : `'${String(value).replaceAll("'", "''")}'`;

const lines = [
  "-- Generated by scripts/generate-d1-seed.mjs. Do not edit manually.",
  "PRAGMA foreign_keys = ON;",
  "",
];
let total = 0;
for (const descriptor of manifest.datasets) {
  const datasetPath = resolve(root, "public/content", descriptor.path);
  const dataset = JSON.parse(await readFile(datasetPath, "utf8"));
  if (dataset.datasetId !== descriptor.id || dataset.version !== descriptor.version || dataset.questions.length !== descriptor.questionCount) {
    throw new Error(`Dataset mismatch: ${descriptor.id}`);
  }
  lines.push(
    `INSERT OR IGNORE INTO datasets(id,version,title,updated_at) VALUES (${sql(descriptor.id)},${descriptor.version},${sql(descriptor.id)},${sql(manifest.updatedAt)});`,
  );
  for (const question of dataset.questions) {
    const values = [
      question.id,
      descriptor.id,
      question.examScopeId,
      question.category,
      question.subcategory,
      question.text,
      question.questionType ?? "single",
      JSON.stringify(question.choices),
      question.answerIndex,
      question.answerIndices ? JSON.stringify(question.answerIndices) : null,
      question.acceptedAnswers ? JSON.stringify(question.acceptedAnswers) : null,
      question.explanation,
      question.source,
      question.tags ? JSON.stringify(question.tags) : null,
      question.weight,
      question.difficulty,
      question.archivedAt,
      1,
      fingerprint(question),
      manifest.updatedAt,
      manifest.updatedAt,
    ];
    lines.push(`INSERT OR IGNORE INTO questions (` +
      `id,dataset_id,exam_scope_id,category,subcategory,text,question_type,choices_json,answer_index,` +
      `answer_indices_json,accepted_answers_json,explanation,source,tags_json,weight,difficulty,archived_at,` +
      `revision,content_hash,created_at,updated_at) VALUES (${values.map(sql).join(",")});`);
    total += 1;
  }
  lines.push("");
}
lines.push(
  `INSERT OR IGNORE INTO content_meta(key,value,updated_at) VALUES ('content_version',${sql(manifest.contentVersion)},${sql(manifest.updatedAt)});`,
  "",
);
await mkdir(dirname(output), { recursive: true });
await writeFile(output, `${lines.join("\n")}\n`, "utf8");
console.log(`Generated ${output} with ${total} questions.`);
